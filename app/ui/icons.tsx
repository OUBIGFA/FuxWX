export type IconName = keyof typeof icons;

const pathCache = new Map<string, Path2D>();
function getPath(d: string): Path2D {
  let cached = pathCache.get(d);
  if (!cached) {
    cached = new Path2D(d);
    pathCache.set(d, cached);
  }
  return cached;
}

export function Icon(p: { name: IconName; color?: string; size?: number }) {
  const side = () => p.size ?? 16;

  return (
    <Canvas
      style={{ width: side(), height: side(), pointerEvents: "none" }}
      draw={(cx, { width, height }) => {
        const box = Math.min(width, height);
        if (box <= 0) return;
        const spec: IconSpec = icons[p.name];
        const color = p.color ?? palette.inkSecondary;
        const scale = box / spec.viewBox;

        cx.save();
        cx.scale(scale, scale);

        if (spec.mode === "fill") {
          cx.fillStyle = color;
          cx.fill(getPath(spec.d));
        } else {
          // Keep small 14-16px strokes crisp at 96 DPI while matching Solar's 1.5/24 weight at larger sizes.
          const strokePx = Math.max(1.25, (box * 1.5) / 24);
          cx.lineWidth = strokePx / scale;
          cx.strokeStyle = color;
          cx.lineCap = "round";
          for (const item of spec.items) {
            if (item.kind === "circle") {
              cx.lineJoin = "miter";
              cx.beginPath();
              cx.arc(item.cx, item.cy, item.r, 0, Math.PI * 2);
              cx.stroke();
            } else {
              cx.lineJoin = item.join ?? "miter";
              cx.stroke(getPath(item.d));
            }
          }
        }

        cx.restore();
      }}
    />
  );
}
